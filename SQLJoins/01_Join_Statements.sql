2. LEFT JOIN:---> IT RETURNS EVERY ROWS FROM THE LEFT TABLE (EMPLOYEE) AND MATCHING ROWS FROM THE RIGHT TABLE(DEPARTMENT)
SELECT
E.EMPNAME,
E.SALARY,
D.DEPTNAME
FROM EMPLOYEES AS E
LEFT JOIN DEPARTMENT AS D
ON E.DEPTID=D.DEPTID;


3. RIGHT JOIN:---> 
IT DEFINES AS THE OR RETURNS ROW FROM THE RIGHT TABLE(DEPARTMENT) AND MATCHING ROWS FROM THE LFET TABLE (EMPLOYEE) 
SELECT 
E.EMPNAME,
E.SALARY,
D.DEPTNAME
FROM EMPLOYEE AS E 
RIGHT JOIN  DEPARTMENT AS D
ON E.DEPTID=D.DEPTID;

4. FULL OUTER JOIN:---> 
IN THIS JOINS IT RETURNS ALL THE MATCHING AND NON MATCHING RECORDS FROM BOTH TABLES.
SELECT 
E.EMPNAME,
E.SALARY,
E.DEPTID AS EMPLOYEEDEPTID,
D.DEPTNAME,
D.DEPTID AS DEPARTMENTDEPTID
FROM EMPLOYEES AS E
FULL OUTER JOIN DEPARTMENT AS D
ON E.DEPTID=D.DEPTID;

